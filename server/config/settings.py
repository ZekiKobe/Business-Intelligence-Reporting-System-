def _jwt_signing_key() -> str:
    """
    PyJWT / HS256 expects a signing key of at least 32 octets (RFC 7518).
    If DJANGO_SECRET_KEY is shorter, derive a stable 64-char hex key for JWT only.
    """
    sk = SECRET_KEY if isinstance(SECRET_KEY, str) else str(SECRET_KEY)
    raw = sk.encode("utf-8")
    if len(raw) >= 32:
        return sk
    return hashlib.sha256(raw).hexdigest()

